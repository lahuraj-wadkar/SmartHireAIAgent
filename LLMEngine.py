#Import request library
#Used to sned HTTP requests to Ollama API

import requests

def ask_llm(prompt):
    """
    Function Name   : ask_llm

    Description     :
    This function sends the given prompt to the locally running Llama3 model through Ollama API
    and returns the generated response.

    Parameters      :
        prompt : Prompt generated by AI Agent
    
    Return Value    :
        Returns response generated by Llama3 model
    """

    #URL of locally runing Ollama API
    #Ollama server listens on port 11434

    url = "http://localhost:11434/api/generate"

    #Payload contains details sent to LLM

    payload = {
            #Name of LLM model
            "model":"llama3",

            #Prompt generated by AI Agent
            "prompt":prompt,

            #stream=False means complete response# will returned at once
            "stream":False
    }

    try:
        print("\n"+"="*100)
        print("\t\t Connecting to Ollama Llama3 Model ...")
        print("Sending prompt to LLM...")
        print("="*100)

        #Send POST reuqest to Ollama API
        response = requests.post(url, json=payload)

        #Raise exception if request failed
        response.raise_for_status()

        print("LLM processing completed successfully.")

        #Convert JSON response into Python dictionary
        data = response.json()

        #Extract actual LLM response
        llm_response = data.get(
            "response",
            "No response generated by LLM."
        )

        return llm_response
    except Exception as e:
        #Error Handling block
        #Executes if Ollama or Llama3 is not working

        return f"""
            ======================================================================
                    LLM Connector Error
            ======================================================================
            Ollama or Llama3 is not runnig properly.

            Please check the following points carefully :

            1. Ollama is installed properly
            2. Llama3 model is downloaded
            3. Ollama server is running
            4. Internet is not required for local execution
            3. Port 11434 is available
            
            ======================================================================
                    Thank you for vising AI Mock Interview Agent
            ======================================================================
         """
